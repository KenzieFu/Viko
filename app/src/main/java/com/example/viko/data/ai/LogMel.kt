package com.example.viko.data.ai

import org.jtransforms.fft.DoubleFFT_1D
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder

/**
 * Turns 16kHz mono PCM into the `[80, 3000]` log-mel spectrogram Whisper's
 * encoder takes as input.
 *
 * This is not in the exported graph — `encoder_model.onnx` declares
 * `input_features [batch, 80, 3000]` as an *input* — so it has to exist here.
 * Every step below mirrors `transformers`' `WhisperFeatureExtractor`, because a
 * feature extractor that is subtly wrong does not fail: it produces a plausible
 * spectrogram and quietly degrades every transcript. [LogMelTest] pins the
 * output against a fingerprint taken from the reference implementation.
 *
 * The filterbank itself is **not** computed here. It is generated by
 * `transformers` in `export_onnx.py mel` and shipped as `mel_filters.bin`
 * alongside each Whisper model — 64KB of float32, mel-major. Reimplementing the
 * Slaney mel scale and its triangular filters in Kotlin would be a second place
 * for the same thing to be wrong.
 */
class LogMel(filterFile: File) {

    companion object {
        const val MELS = 80
        const val N_FFT = 400
        const val HOP = 160
        const val SAMPLE_RATE = 16_000

        /** Whisper is a fixed-window model: exactly 30s, zero-padded. */
        const val N_SAMPLES = SAMPLE_RATE * 30
        const val FRAMES = N_SAMPLES / HOP          // 3000

        /**
         * Trailing silence appended after the speech, in frames — 5 seconds.
         *
         * **Load-bearing, not a safety margin.** Whisper is trained on 30s windows
         * where speech is followed by silence, and it uses that silence to decide
         * the utterance ended. Cut the window to exactly the speech and it never
         * emits `<|endoftext|>`: it loops the same sentence until the token cap.
         * Measured on the reference clip (4.6s of speech):
         *
         * ```
         *   +0.0s padding -> 220 tokens, ran away, sentence repeated 9 times
         *   +1.4s         ->  24 tokens, terminated, one word off
         *   +5.4s         ->  23 tokens, terminated, exact match with the reference
         *  +25.4s (full)  ->  23 tokens, terminated, exact match
         * ```
         *
         * So this buys correctness, and everything past it only buys encoder time.
         */
        const val PAD_FRAMES = 500

        /**
         * Floor on the whole window. A one-second burst still gets a window with
         * room around it, which is both what the model expects and cheap.
         */
        const val MIN_FRAMES = 700

        /** `n_fft / 2 + 1` — the one-sided spectrum. */
        const val BINS = N_FFT / 2 + 1              // 201

        /**
         * **Periodic** Hann, `0.5 - 0.5*cos(2*pi*n/N)`, not the symmetric
         * `np.hanning(400)`. transformers' `window_function(..., periodic=True)`
         * is the default and the two differ at every sample.
         */
        private val WINDOW = DoubleArray(N_FFT) {
            0.5 - 0.5 * kotlin.math.cos(2.0 * Math.PI * it / N_FFT)
        }
    }

    /** `[MELS][BINS]`, mel-major so each output bin is one contiguous dot product. */
    private val filters: Array<FloatArray> = run {
        val bytes = filterFile.readBytes()
        val expected = MELS * BINS * 4
        require(bytes.size == expected) {
            "mel_filters.bin is ${bytes.size} bytes, expected $expected " +
                "($MELS x $BINS float32) — regenerate with `export_onnx.py mel`"
        }
        val buf = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN).asFloatBuffer()
        Array(MELS) { FloatArray(BINS).also(buf::get) }
    }

    /**
     * The first and last non-zero coefficient of each mel filter.
     *
     * Mel filters are overlapping triangles, so a row of 201 coefficients is
     * mostly zeros — the low bins span a handful of frequencies each. Walking only
     * the non-zero span turns the 80 x 201 x 3000 inner loop into roughly a
     * fifteenth of the multiply-adds, for the same result. Measured: 614ms of mel
     * extraction is the second-largest cost in the cascade after MT, so this is
     * worth the eight lines.
     */
    private val spans: Array<IntArray> = Array(MELS) { m ->
        val row = filters[m]
        var lo = 0
        while (lo < BINS && row[lo] == 0f) lo++
        var hi = BINS - 1
        while (hi >= lo && row[hi] == 0f) hi--
        intArrayOf(lo, hi + 1)
    }

    private val fft = DoubleFFT_1D(N_FFT.toLong())

    /**
     * PCM16 as it arrives from the badge, scaled to the [-1, 1] floats the
     * feature extractor expects.
     */
    fun fromPcm16(pcm: ByteArray, length: Int = pcm.size, frames: Int = FRAMES): FloatArray {
        val samples = FloatArray(length / 2)
        val buf = ByteBuffer.wrap(pcm, 0, length).order(ByteOrder.LITTLE_ENDIAN)
        for (i in samples.indices) samples[i] = buf.short / 32768f
        return extract(samples, frames)
    }

    /**
     * How many mel frames to compute for [samples] of audio.
     *
     * Whisper is trained on a 30s window and the stock export bakes that in, but
     * the encoder re-exported by `export_encoder_dynamic.py` accepts any length —
     * and its cost is quadratic in that length, so handing it 30s of mostly silence
     * for a 4s utterance is the single most expensive mistake available here.
     *
     * The window is the speech plus [PAD_FRAMES] of trailing silence, which the
     * model needs in order to stop — see that constant. Rounded up to even because
     * the encoder's second convolution has stride 2, and clamped to the 30s the
     * model was trained on.
     */
    fun framesFor(samples: Int): Int {
        val speech = (samples + HOP - 1) / HOP
        val needed = speech + PAD_FRAMES
        val even = needed + (needed and 1)
        return even.coerceIn(MIN_FRAMES, FRAMES)
    }

    /**
     * Returns `[MELS * frames]` in row-major mel-then-time order, ready to become
     * an ONNX tensor of shape `[1, 80, frames]`.
     *
     * [frames] defaults to Whisper's full 30s window. Pass [framesFor] to pay only
     * for the speech that actually happened.
     */
    fun extract(audio: FloatArray, frames: Int = FRAMES): FloatArray {
        require(frames in MIN_FRAMES..FRAMES && frames % 2 == 0) {
            "frames must be even and in $MIN_FRAMES..$FRAMES, got $frames"
        }
        // Anything past the window is cut, anything short is zero-padded. Padding
        // with silence rather than looping matters — the model was trained this way
        // and reads the padding as "nothing more was said".
        val nSamples = frames * HOP
        val padded = DoubleArray(nSamples)
        for (i in 0 until minOf(audio.size, nSamples)) padded[i] = audio[i].toDouble()

        // center=True: reflect-pad by n_fft/2 either side so frame t is centred on
        // sample t*hop. Reflection, not zeros — zeros would put a false transient
        // at both ends of every clip.
        val half = N_FFT / 2
        val signal = DoubleArray(nSamples + N_FFT)
        for (i in 0 until half) signal[i] = padded[half - i]
        System.arraycopy(padded, 0, signal, half, nSamples)
        for (i in 0 until half) signal[nSamples + half + i] = padded[nSamples - 2 - i]

        val out = FloatArray(MELS * frames)
        val frame = DoubleArray(N_FFT)
        val power = DoubleArray(BINS)
        var globalMax = Float.NEGATIVE_INFINITY

        // The reference computes 3001 frames and drops the last one. Producing 3000
        // directly is the same thing, since the discarded frame feeds nothing.
        for (t in 0 until frames) {
            val start = t * HOP
            for (i in 0 until N_FFT) frame[i] = signal[start + i] * WINDOW[i]
            fft.realForward(frame)

            // JTransforms packs a real forward transform as
            //   frame[0]      = Re[0]          (DC, imaginary part is zero)
            //   frame[1]      = Re[n/2]        (Nyquist, tucked into the unused slot)
            //   frame[2k],[2k+1] = Re[k], Im[k]
            power[0] = frame[0] * frame[0]
            power[BINS - 1] = frame[1] * frame[1]
            for (k in 1 until BINS - 1) {
                val re = frame[2 * k]
                val im = frame[2 * k + 1]
                power[k] = re * re + im * im
            }

            for (m in 0 until MELS) {
                val row = filters[m]
                val span = spans[m]
                var sum = 0.0
                for (k in span[0] until span[1]) sum += row[k] * power[k]
                // mel_floor 1e-10 before the log, so silence is finite rather than -inf.
                val v = kotlin.math.log10(maxOf(sum, 1e-10)).toFloat()
                out[m * frames + t] = v
                if (v > globalMax) globalMax = v
            }
        }

        // Dynamic-range clamp then rescale, both taken from the reference. The floor
        // is relative to this clip's own peak, so it must run after every frame.
        val floor = globalMax - 8.0f
        for (i in out.indices) out[i] = (maxOf(out[i], floor) + 4.0f) / 4.0f
        return out
    }
}
